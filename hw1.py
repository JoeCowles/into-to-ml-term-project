"""## Task 4.1 — Attention (20 pts)

$$\mathrm{Attention}(Q,K,V) = \mathrm{softmax}\!\left(\frac{QK^{\top}}{\sqrt{d_k}} + M_{\mathrm{causal}}\right)V$$

`q`, `k`, `v` have shape `(b, n_head, t, d_k)`:

* `b` — batch size, how many independent sequences are processed at once
* `n_head` — number of attention heads, each with its own $W_Q, W_K, W_V$, computed in parallel
* `t` — number of positions in the context (at most `block_size`)
* `d_k` — head size, `n_embd // n_head`; the queries and keys of one head live in $\mathbb{R}^{d_k}$

`q @ k.transpose(-2, -1)` contracts the last axis and gives, per batch element and head, a
`(t, t)` matrix of scores: entry $(i,j)$ is how much position $i$ attends to position $j$.
`mask` is `True` where attention is allowed; setting the other entries to $-\infty$ before the
softmax is the same as adding $M_{\mathrm{causal}}$.
"""

def attention(q, k, v, mask):
    """Scaled dot-product attention.

    Args:
        q, k, v: tensors of shape (b, n_head, t, d_k)
        mask:    boolean tensor of shape (t, t), True where attention is allowed

    Returns:
        tensor of shape (b, n_head, t, d_k)

    Steps: scores = q @ k^T / sqrt(d_k); set the disallowed entries to -inf
    (torch.Tensor.masked_fill); softmax over the last axis; multiply by v.
    """
    k_t = k.transpose(-2, -1)

    d_k = q.size(-1)

    scores = q @ k_t / math.sqrt(d_k)

    scores = scores.masked_fill(~mask, float("-inf"))

    weights = torch.softmax(scores, dim=-1)

    return weights @ v

"""## Task 4.2 — Causal mask (15 pts)

On the slides the mask is additive,

$$\left(M_{\mathrm{causal}}\right)_{ij} = \begin{cases} 0, & j \le i \\ -\infty, & j > i \end{cases}$$

so that after the softmax every future position gets exactly zero weight. Here you return the
equivalent boolean matrix: `True` where $j \le i$. You only have to build the matrix; the provided
module takes care of placing it correctly.
"""

def causal_mask(t):
    """Return the (t, t) boolean mask that allows position i to attend to positions j <= i.

    Hint: torch.tril and torch.ones, with dtype=torch.bool.
    """
    return torch.tril(torch.ones(t, t, dtype=torch.bool))

