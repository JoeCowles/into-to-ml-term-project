def kl_joint(p, q):
    """KL divergence D_KL(p || q) between two joint distributions.

    Args:
        p, q: arrays of the same shape, here (2, 2, 2), each summing to one. The sum in the
              definition runs over all three variables, i.e. over every entry of the table.

    Returns:
        float: the divergence in nats. Use the conventions 0 * log(0 / q) = 0 and
               p * log(p / 0) = +inf for p > 0.
    """

    sum = 0.0

    for i in range(len(p)):
        for j in range(len(p[i])):
            for k in range(len(p[i][j])):
                if p[i][j][k] != 0:
                    sum += p[i][j][k] * math.log(p[i][j][k] / q[i][j][k])
                else:
                    sum += 0
    return sum

