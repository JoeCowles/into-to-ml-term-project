def joint_sample(p, n, rng):
    """Draw n i.i.d. triples (x, y, z) from the joint distribution p.

    Flatten the table, draw a flat index with the inverse-CDF method (draw u ~ U[0, 1) and take
    the smallest index k with u < sum(p_flat[:k+1])), then map that index back to a triple.
    Only rng.random may be used as a source of randomness; np.random.choice may be used to
    check your implementation, but not inside it.
    Hint: np.cumsum, np.searchsorted and np.unravel_index make this short.

    Returns:
        integer array of shape (n, 3), one row per sampled triple.
    """
    p_flat = p.ravel()
    cdf = np.cumsum(p_flat)
    rand = rng.random(n)
    k = np.searchsorted(cdf, rand, side="right")
    x, y, z = np.unravel_index(k, p.shape)
    return np.stack([x, y, z], axis=1)


def empirical_joint(samples, shape):
    """Estimated joint distribution: p_hat[x, y, z] = (count of (x,y,z)) / n.

    Args:
        samples: integer array of shape (n, 3), as returned by joint_sample.
        shape:   shape of the table to return, here (2, 2, 2).

    Returns:
        array of the given shape, summing to one. Triples that were never observed get
        probability zero. Hint: np.ravel_multi_index and np.bincount.
    """
    flat_idx = np.ravel_multi_index(samples.T, shape)
    counts = np.bincount(flat_idx, minlength=int(np.prod(shape)))
    return counts.reshape(shape) / len(samples)

