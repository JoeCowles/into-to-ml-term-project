def gaussian_entropy(sigma):
    """Closed-form differential entropy of N(mu, sigma), in nats.

    Compute log|sigma| from the Cholesky factor: sigma = L @ L.T (np.linalg.cholesky) and
    log|sigma| = 2 * sum(log(diag(L))).
    """
    d = sigma.shape[0]

    L = np.linalg.cholesky(sigma)

    det = 2 * np.sum(np.log(np.diag(L)))

    return 0.5 * d * (1 + np.log(2*np.pi)) + 0.5 * det

def gaussian_sample(mu, sigma, n, rng):
    """Draw n samples from N(mu, sigma), as an array of shape (n, d).

    Use x = mu + L @ eps with eps ~ N(0, I) from rng.standard_normal.
    """
    d = sigma.shape[0]
    L = np.linalg.cholesky(sigma)
    eps = rng.standard_normal(size=(n, d))
    return mu + eps @ L.T



def gaussian_logpdf(x, mu, sigma):

    d = sigma.shape[0]
    L = np.linalg.cholesky(sigma)
    det = 2 * np.sum(np.log(np.diag(L)))

    diff = x - mu
    z = np.linalg.solve(L, diff.T)
    maha = np.sum(z**2, axis=0)

    return -0.5 * d * np.log(2 * np.pi) - 0.5 * det - 0.5 * maha

